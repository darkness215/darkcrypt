#!/usr/bin/env python3
"""
build_id.py — F22: build-to-build randomization for darkcrypt.

Generates a random build_id.h containing a 16-byte BUILD_ID baked into a
dedicated .buildid section (via __attribute__((section))). Two builds of the
same source produce different binaries, defeating hash-once-match-forever.

Usage:
    python3 tools/build_id.py > build_id.h

The generated header is included by aes-main.c (via #include "build_id.h")
when DARKCRYPT_BUILD_ID is defined (the release-random Makefile target sets it).
The BUILD_ID itself is not read at runtime — it only perturbs the binary so
no two builds are byte-identical.
"""
import os
import sys

def main():
    bid = os.urandom(16)
    hex_bytes = ", ".join(f"0x{b:02X}" for b in bid)
    print("/* AUTO-GENERATED by tools/build_id.py — do not edit. */")
    print("/* F22: per-build randomization. The bytes below are baked into a")
    print(" * .buildid section so two builds of the same source differ. */")
    print(f'static __attribute__((section(".buildid"))) '
          f'const unsigned char BUILD_ID[16] = {{ {hex_bytes} }};')

if __name__ == "__main__":
    main()